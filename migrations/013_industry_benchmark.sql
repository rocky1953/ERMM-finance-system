-- =======================================================================
-- 013  Industry Benchmark（同业标杆）
-- -----------------------------------------------------------------------
-- 为每个核心 KPI 提供同业分位数据（P10 / P25 / Median / P75 / P90），
-- 供前端在 KPI 卡片渲染「同业区间条」与「优于/劣于同业」徽标。
--
-- 数据来源：TEJ / 台湾制造业 & 批发零售业公开财务比率中位数，
--           每年 Q1 建议更新一次；字段均允许 NULL，缺省表示该 KPI
--           在该行业没有可用标杆，前端会优雅降级为不显示同业区块。
-- =======================================================================

CREATE TABLE IF NOT EXISTS industry_benchmark (
    uid            INT AUTO_INCREMENT PRIMARY KEY,
    kpi_id         VARCHAR(50)  NOT NULL COMMENT '对应 routes/kpiQuery.js 的 FORMULAS id',
    industry       VARCHAR(50)  NOT NULL COMMENT '制造业 / 批发零售业 / 全体',
    year           SMALLINT     NOT NULL COMMENT '数据年度，如 2025',
    p10            DECIMAL(18,4) DEFAULT NULL COMMENT '同业第 10 百分位',
    p25            DECIMAL(18,4) DEFAULT NULL COMMENT '同业第 25 百分位',
    median         DECIMAL(18,4) DEFAULT NULL COMMENT '同业中位数',
    p75            DECIMAL(18,4) DEFAULT NULL COMMENT '同业第 75 百分位',
    p90            DECIMAL(18,4) DEFAULT NULL COMMENT '同业第 90 百分位',
    note           VARCHAR(200) DEFAULT NULL COMMENT '备注 / 数据来源',
    created_at     DATETIME     DEFAULT CURRENT_TIMESTAMP,
    updated_at     DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_kpi_ind_year (kpi_id, industry, year)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='同业标杆分位数据';

