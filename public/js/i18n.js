    setLang(lang) {
        this._lang = lang;
        localStorage.setItem('ermm_lang', lang);
        this.applyUI();
        if (typeof navigate === 'function' && typeof currentPage !== 'undefined') {
            navigate(currentPage);
        }
    },

    applyUI() {
        // 更新 HTML lang
        document.documentElement.lang = this._lang;

        // 更新侧边栏
        document.querySelectorAll('[data-i18n]').forEach(el => {
            el.textContent = this.t(el.dataset.i18n);
        });

        // 更新顶栏
        const titleEl = document.getElementById('pageTitle');
        if (titleEl && currentPage) {
            titleEl.textContent = this.t('page.' + currentPage);
        }

        // 更新 BU 下拉
        const bu = document.getElementById('globalBU');
        if (bu) bu.title = this.t('topbar.bu');
        const buLabel = document.getElementById('buLabel');
        if (buLabel) buLabel.textContent = this.t('topbar.bu');
        const monthLabel = document.getElementById('monthLabel');
        if (monthLabel) monthLabel.textContent = this.t('topbar.month');
        const langLabel = document.getElementById('langLabel');
        if (langLabel) langLabel.textContent = this.t('topbar.lang');
    }
