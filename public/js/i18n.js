    /** 把 DB 存的中文狀態值轉成當前語言顯示 */
    statusLabel(kind, chs) {
        const m = this._statusMaps[kind];
        if (!m || !chs) return chs || '-';
        const key = m[chs];
        return key ? this.t(key) : chs;
    },

    /** 給前端 select 用：value=中文存 DB，textContent=當前語言 */
    statusOptions(kind) {
        const m = this._statusMaps[kind];
        if (!m) return [];
        return Object.keys(m).map(chs => ({ value: chs, label: this.t(m[chs]) }));
    },

    t(key) {
        const dict = this._dict[this._lang] || this._dict['zh-TW'];
        return dict[key] || key;
    },

